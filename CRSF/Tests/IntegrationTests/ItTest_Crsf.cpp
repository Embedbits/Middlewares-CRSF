/*--------------------------- Transport layer --------------------------------*/

/**
 * \brief   Frame with invalid CRC is dropped, the following frame is received.
 *
 * \details RC side sends RC channels frame with inverted frame CRC and link statistics
 *          frame directly behind it (both queued, sent back to back).
 *
 * \par Expected results
 * - Only the link statistics frame received by the flight controller.
 * - CRC error(s) counted by the transport layer of the flight controller, RC channels not changed.
 */
void It_Crsf_CorruptedFrame_Dropped_FollowingFrameReceived( void )
{
    static uint8_t  validFrame[ CRSF_FRAME_MAX_LEN ];
    uint8_t         payload[ CRSF_PAYLOAD_MAX_LEN ] = { 0u };
    crsf_RcChannels_t channels;

    for( uint8_t chIdx = 0u; CRSF_RC_CHANNELS_CNT > chIdx; chIdx++ )
    {
        channels.Channels[ chIdx ] = 1234u;
    }

    It_Crsf_Init( USART_XFER_MODE_DMA );

    It_Crsf_Pack_RcChannels( channels, payload );
    const crsf_MsgLength_t corruptedLen = It_Crsf_Build_Frame( itCrsf_Frame, CRSF_FRAMETYPE_RC_CHANNELS_PACKED, payload, 22u );
    itCrsf_Frame[ corruptedLen - 1u ] ^= 0xFFu;

    const uint8_t linkStats[] = { 1u, 2u, 3u, 4u, 5u, 6u, 7u, 8u, 9u, 10u };
    const crsf_MsgLength_t validLen = It_Crsf_Build_Frame( validFrame, CRSF_FRAMETYPE_LINK_STATISTICS, linkStats, sizeof( linkStats ) );

    TEST_ASSERT_EQUAL( CRSF_REQUEST_OK, itCrsf_HandsetTl.Send_RawFrame( itCrsf_Frame, corruptedLen ) );
    TEST_ASSERT_EQUAL( CRSF_REQUEST_OK, itCrsf_HandsetTl.Send_RawFrame( validFrame, validLen ) );
    It_Crsf_Run( 10u );

    TEST_ASSERT_EQUAL_UINT32( 1u, itCrsf_FcLog.Cnt );
    It_Crsf_Check_FcFrame( 0u, validFrame, validLen );
    /* Resynchronization drops byte by byte - sync-like bytes in payload can add further CRC errors */
    TEST_ASSERT_TRUE( 1u <= itCrsf_FcTl.Get_StatCounter().CrcErrorCnt );
    TEST_ASSERT_EQUAL_UINT32( 0u, itCrsf_RcCallbackCnt );
    TEST_ASSERT_EQUAL_UINT32( 1u, itCrsf_LinkStatsCnt );
    TEST_ASSERT_EQUAL_UINT32( corruptedLen + validLen, itCrsf_FcPhy.Get_RxByteCnt() );
}

