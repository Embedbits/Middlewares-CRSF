/**
 * \brief Records received frame - into the log or compares it with the stream of sent frames
 *
 * \param log    [in/out]: Log of the receiving side
 * \param stream [in/out]: Stream of frames sent to the receiving side
 * \param frame      [in]: Received frame
 */
static void It_Crsf_Record( itCrsf_FrameLog_t &log, itCrsf_Stream_t &stream, const crsf_Frame_t *frame )
{
    if( true == stream.Active )
    {
        bool equal = ( 0u < stream.Count ) && ( frame->RawLen == stream.Len[ stream.Head ] );

        for( crsf_MsgLength_t byteIdx = 0u; ( true == equal ) && ( frame->RawLen > byteIdx ); byteIdx++ )
        {
            equal = ( frame->Raw[ byteIdx ] == stream.Frames[ stream.Head ][ byteIdx ] );
        }

        if( false == equal )
        {
            stream.MismatchCnt++;
        }
        else
        {
            /* Frame received as sent */
        }

        if( 0u < stream.Count )
        {
            stream.Head = (uint8_t)( ( stream.Head + 1u ) % ( sizeof( stream.Len ) / sizeof( stream.Len[ 0u ] ) ) );
            stream.Count--;
        }
        else
        {
            /* Unexpected frame - counted as mismatch */
        }

        stream.RcvdCnt++;
    }
    else if( ( sizeof( log.RawLen ) / sizeof( log.RawLen[ 0u ] ) ) > log.Cnt )
    {
        for( crsf_MsgLength_t byteIdx = 0u; ( frame->RawLen > byteIdx ) && ( CRSF_FRAME_MAX_LEN > byteIdx ); byteIdx++ )
        {
            log.Raw[ log.Cnt ][ byteIdx ] = frame->Raw[ byteIdx ];
        }

        log.RawLen[ log.Cnt ] = frame->RawLen;
    }
    else
    {
        /* Log is full - frame only counted */
    }

    log.Cnt++;
}


/**
 * \brief Generates random frames into transmit queue of the transport layer while the
 *        queue and the stream FIFO have free space
 *
 * \param stream         [in/out]: Stream of the direction
 * \param transportLayer [in]: Sending transport layer
 * \param framesCnt      [in]: Count of frames of the whole stream
 */
static void It_Crsf_Stream_Fill( itCrsf_Stream_t &stream, Crsf::TransportLayer &transportLayer, uint32_t framesCnt )
{
    const uint8_t fifoSize = (uint8_t)( sizeof( stream.Len ) / sizeof( stream.Len[ 0u ] ) );

    while( ( framesCnt > stream.SentCnt ) && ( fifoSize > stream.Count ) && ( 0u < transportLayer.Get_TxQueueFreeCnt() ) )
    {
        const uint8_t    slot = (uint8_t)( ( stream.Head + stream.Count ) % fifoSize );
        uint8_t          payload[ CRSF_PAYLOAD_MAX_LEN ];
        crsf_MsgLength_t frameLen = 0u;

        if( 0u == It_Crsf_Random( stream.RandomState, 8u ) )
        {
            /* Extended frame for other device */
            const crsf_MsgLength_t payloadLen = (crsf_MsgLength_t)It_Crsf_Random( stream.RandomState, CRSF_EXT_PAYLOAD_MAX_LEN + 1u );

            for( crsf_MsgLength_t byteIdx = 0u; payloadLen > byteIdx; byteIdx++ )
            {
                payload[ byteIdx ] = (uint8_t)It_Crsf_Random( stream.RandomState, 256u );
            }

            frameLen = It_Crsf_Build_ExtFrame( stream.Frames[ slot ], itCrsf_RandomExtType, itCrsf_RandomExtDest,
                                               (uint8_t)( itCrsf_RandomExtDest + 1u ), payload, payloadLen );
        }
        else
        {
            const uint8_t          frameType  = itCrsf_RandomTypes[ It_Crsf_Random( stream.RandomState, sizeof( itCrsf_RandomTypes ) ) ];
            const crsf_MsgLength_t payloadLen = (crsf_MsgLength_t)It_Crsf_Random( stream.RandomState, CRSF_PAYLOAD_MAX_LEN + 1u );

            for( crsf_MsgLength_t byteIdx = 0u; payloadLen > byteIdx; byteIdx++ )
            {
                payload[ byteIdx ] = (uint8_t)It_Crsf_Random( stream.RandomState, 256u );
            }

            frameLen = It_Crsf_Build_Frame( stream.Frames[ slot ], frameType, payload, payloadLen );
        }

        stream.Len[ slot ] = frameLen;

        if( CRSF_REQUEST_OK == transportLayer.Send_RawFrame( stream.Frames[ slot ], frameLen ) )
        {
            stream.Count++;
            stream.SentCnt++;
        }
        else
        {
            /* Queue full - next attempt in next task */
            break;
        }
    }
}


/**
 * \brief Returns pseudo-random number (xorshift32)
 *
 * \param state [in/out]: State of the generator
 * \param range     [in]: Range of the result (> 0)
 *
 * \return Number 0 ... range - 1
 */
static uint32_t It_Crsf_Random( uint32_t &state, uint32_t range )
{
    state ^= state << 13u;
    state ^= state >> 17u;
    state ^= state << 5u;

    return ( state % range );
}


/**
 * \brief Returns true if random traffic has transport failure - USART error, invalid
 *        or lost frame (frame different from the expected one)
 */
static bool It_Crsf_TransportFailed( void )
{
    return ( ( 0u != itCrsf_ToFcStream.MismatchCnt                       ) ||
             ( 0u != itCrsf_ToHandsetStream.MismatchCnt                  ) ||
             ( 0u != itCrsf_HandsetPhy.Get_ErrorCnt()                    ) ||
             ( 0u != itCrsf_FcPhy.Get_ErrorCnt()                         ) ||
             ( 0u != itCrsf_HandsetTl.Get_StatCounter().CrcErrorCnt      ) ||
             ( 0u != itCrsf_FcTl.Get_StatCounter().CrcErrorCnt           ) ||
             ( 0u != itCrsf_HandsetTl.Get_StatCounter().LengthErrorCnt   ) ||
             ( 0u != itCrsf_FcTl.Get_StatCounter().LengthErrorCnt        ) ||
             ( 0u != itCrsf_HandsetTl.Get_StatCounter().DiscardedByteCnt ) ||
             ( 0u != itCrsf_FcTl.Get_StatCounter().DiscardedByteCnt      ) );
}


/**
 * \brief Sends random frames in both directions and checks their reception
 *
 * \param framesCnt [in]: Count of frames of every direction
 */
static void It_Crsf_RandomTraffic( uint32_t framesCnt )
{
    itCrsf_Stream_t * const streams[] = { &itCrsf_ToFcStream, &itCrsf_ToHandsetStream };

    for( uint8_t streamIdx = 0u; ( sizeof( streams ) / sizeof( streams[ 0u ] ) ) > streamIdx; streamIdx++ )
    {
        streams[ streamIdx ]->Head        = 0u;
        streams[ streamIdx ]->Count       = 0u;
        streams[ streamIdx ]->SentCnt     = 0u;
        streams[ streamIdx ]->RcvdCnt     = 0u;
        streams[ streamIdx ]->MismatchCnt = 0u;
        streams[ streamIdx ]->RandomState = 0x9E3779B9u + ( streamIdx * 0x01234567u );
        streams[ streamIdx ]->Active      = true;
    }

    It_Crsf_HaltGuard_Mark();

    /* Traffic ends with the first transport failure - halt detection covers the time up to the failure */
    (void)It_Crsf_RunUntil( [ framesCnt ]()
    {
        It_Crsf_Stream_Fill( itCrsf_ToFcStream,      itCrsf_HandsetTl, framesCnt );
        It_Crsf_Stream_Fill( itCrsf_ToHandsetStream, itCrsf_FcTl,      framesCnt );

        return ( ( ( framesCnt <= itCrsf_ToFcStream.RcvdCnt ) && ( framesCnt <= itCrsf_ToHandsetStream.RcvdCnt ) ) ||
                 ( true == It_Crsf_TransportFailed() ) );
    }, itCrsf_RandomTimeout );

    const bool finished = ( framesCnt <= itCrsf_ToFcStream.RcvdCnt ) && ( framesCnt <= itCrsf_ToHandsetStream.RcvdCnt );

    It_Crsf_Retry_IfHalted( ( false == finished ) || ( true == It_Crsf_TransportFailed() ) );

    /* Possible surplus frames */
    It_Crsf_Run( 5u );

    TEST_ASSERT_TRUE_MESSAGE( finished, "Random traffic not finished (timeout or transport failure)" );
    TEST_ASSERT_EQUAL_UINT32_MESSAGE( framesCnt, itCrsf_ToFcStream.SentCnt,           "Frames sent to FC" );
    TEST_ASSERT_EQUAL_UINT32_MESSAGE( framesCnt, itCrsf_ToFcStream.RcvdCnt,           "Frames received by FC" );
    TEST_ASSERT_EQUAL_UINT32_MESSAGE( 0u,        itCrsf_ToFcStream.MismatchCnt,       "Frames received by FC different from sent" );
    TEST_ASSERT_EQUAL_UINT32_MESSAGE( framesCnt, itCrsf_ToHandsetStream.SentCnt,      "Frames sent to RC side" );
    TEST_ASSERT_EQUAL_UINT32_MESSAGE( framesCnt, itCrsf_ToHandsetStream.RcvdCnt,      "Frames received by RC side" );
    TEST_ASSERT_EQUAL_UINT32_MESSAGE( 0u,        itCrsf_ToHandsetStream.MismatchCnt,  "Frames received by RC side different from sent" );
    TEST_ASSERT_EQUAL_UINT32( framesCnt, itCrsf_FcTl.Get_StatCounter().FramesRcvdCnt );
    TEST_ASSERT_EQUAL_UINT32( framesCnt, itCrsf_HandsetTl.Get_StatCounter().FramesRcvdCnt );
    It_Crsf_Check_NoErrors();
}

