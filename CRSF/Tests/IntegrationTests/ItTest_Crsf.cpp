/**
 * \author Mr.Nobody
 * \file ItTest_Crsf.cpp
 * \ingroup Crsf
 * \brief Integration tests of CRSF stack on target (RC side <-> flight controller).
 *
 * Two complete CRSF stacks run on the same MCU, each one on its own USART.
 * The USARTs are cross connected by wires on the board, so every frame passes
 * real USART hardware (USART MCAL, interrupt / DMA data handling, 416666 Bd):
 * - RC side (master, "handset", address 0xEA) - sends RC channels, link
 *   statistics, parameter requests and direct commands, receives telemetry.
 * - Flight controller (slave, address 0xC8) - RC channels with failsafe,
 *   telemetry reception, device parameters and direct commands handlers,
 *   sends telemetry.
 *
 * Frames are generated by the test (frame CRC 0xD5 and command CRC 0xBA are
 * calculated by the test independently of the stack) or by the stack API.
 * Every received frame is recorded by the frame callback of the receiving
 * application core and compared byte by byte with the frame expected by the
 * test, decoded values are checked by the handler callbacks. Responses of the
 * flight controller (device information, parameter entries, command ACK) are
 * compared with the responses expected by the test.
 *
 * Required wiring (NUCLEO-H503RB):
 *
 *      RC side  USART1 TX  PB14  ------>  PB1  USART2 RX  FC
 *      RC side  USART1 RX  PB15  <------  PA2  USART2 TX  FC
 *
 * Used resources (see board configuration below):
 * - USART1 (RC side), USART2 (flight controller), USART interrupts
 * - Data transfer by DMA - interrupt mode overruns at 416666 Bd (known defect)
 * - GPDMA1 channels 0 - 3 (both ports)
 * - TIM2 - 1 ms time base of CRSF tasks
 * - TIM6 - detection of debug halts (runs while the core is halted)
 *
 * Debug halts: the host (probe-rs) halts the core for a few milliseconds on
 * every read of the result mailbox. Interrupts are not served during the halt,
 * the USART receiver can overrun and frames get lost. TIM2 is frozen during
 * the halt, TIM6 is not - their difference is the halt time. Random traffic
 * ends with the first transport failure (USART error, lost / invalid frame) or
 * timeout. If the core was halted until then, the whole test case is repeated
 * after reset (next stage, max. 3 times, reported by INFO line). Failure
 * without halt always fails the test case.
 */

