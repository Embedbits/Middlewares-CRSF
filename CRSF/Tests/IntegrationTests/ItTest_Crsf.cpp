/**
 * \brief Time base hook - RC side sends RC channels every 4 ms
 *
 * \param timeMs [in]: Time since start of waiting [ms]
 */
static void It_Crsf_RcTickHook( uint32_t timeMs )
{
    if( 0u == ( timeMs % itCrsf_RcPeriodMs ) )
    {
        crsf_RcChannels_t channels;

        for( uint8_t chIdx = 0u; CRSF_RC_CHANNELS_CNT > chIdx; chIdx++ )
        {
            channels.Channels[ chIdx ] = (uint16_t)( ( itCrsf_RcSentCnt + chIdx ) & CRSF_RC_CHANNEL_VALUE_MAX );
        }

        if( CRSF_REQUEST_OK == itCrsf_HandsetTelemetryTx.Send_RcChannels( channels ) )
        {
            itCrsf_RcSentCnt++;
        }
    }
}


