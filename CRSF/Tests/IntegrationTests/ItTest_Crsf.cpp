/*----------------------------- Frame generation -----------------------------*/

/**
 * \brief Builds frame with short header: sync byte, length, type, payload, frame CRC
 *
 * \param frame      [out]: Frame buffer (CRSF_FRAME_MAX_LEN bytes)
 * \param frameType  [in]: Frame type
 * \param payload    [in]: Payload (can be null for 0 bytes)
 * \param payloadLen [in]: Payload length
 *
 * \return Frame length
 */
static crsf_MsgLength_t It_Crsf_Build_Frame( uint8_t *frame, uint8_t frameType, const uint8_t *payload, crsf_MsgLength_t payloadLen )
{
    frame[ 0u ] = CRSF_SYNC_BYTE;
    frame[ 1u ] = (uint8_t)( payloadLen + 2u );
    frame[ 2u ] = frameType;

    for( crsf_MsgLength_t byteIdx = 0u; payloadLen > byteIdx; byteIdx++ )
    {
        frame[ 3u + byteIdx ] = payload[ byteIdx ];
    }

    frame[ 3u + payloadLen ] = It_Crsf_Crc8( 0u, itCrsf_FrameCrcPoly, &frame[ 2u ], (crsf_MsgLength_t)( payloadLen + 1u ) );

    return ( (crsf_MsgLength_t)( payloadLen + 4u ) );
}


/**
 * \brief Builds frame with extended header (destination and origin address)
 *
 * \return Frame length
 */
static crsf_MsgLength_t It_Crsf_Build_ExtFrame( uint8_t *frame, uint8_t frameType, uint8_t destAddr, uint8_t origAddr,
                                                const uint8_t *payload, crsf_MsgLength_t payloadLen )
{
    uint8_t extPayload[ CRSF_PAYLOAD_MAX_LEN ];

    extPayload[ 0u ] = destAddr;
    extPayload[ 1u ] = origAddr;

    for( crsf_MsgLength_t byteIdx = 0u; payloadLen > byteIdx; byteIdx++ )
    {
        extPayload[ 2u + byteIdx ] = payload[ byteIdx ];
    }

    return ( It_Crsf_Build_Frame( frame, frameType, extPayload, (crsf_MsgLength_t)( payloadLen + 2u ) ) );
}


/**
 * \brief Calculates CRC-8 (MSB first, no final XOR) bit by bit - independent of the
 *        implementation of the stack
 *
 * \param crc        [in]: Initial value / CRC of previous data
 * \param polynomial [in]: Polynomial (0xD5 frame CRC, 0xBA command CRC)
 * \param data       [in]: Data
 * \param length     [in]: Count of bytes
 *
 * \return CRC
 */
static uint8_t It_Crsf_Crc8( uint8_t crc, uint8_t polynomial, const uint8_t *data, crsf_MsgLength_t length )
{
    for( crsf_MsgLength_t byteIdx = 0u; length > byteIdx; byteIdx++ )
    {
        crc ^= data[ byteIdx ];

        for( uint8_t bitIdx = 0u; 8u > bitIdx; bitIdx++ )
        {
            crc = ( 0u != ( crc & 0x80u ) ) ? (uint8_t)( ( crc << 1u ) ^ polynomial ) : (uint8_t)( crc << 1u );
        }
    }

    return ( crc );
}


/**
 * \brief Packs 16 RC channels (11 bits, little endian, LSB first) into 22 bytes
 *
 * \param channels [in]: Raw channel values
 * \param payload [out]: Packed payload (22 bytes)
 */
static void It_Crsf_Pack_RcChannels( const crsf_RcChannels_t &channels, uint8_t *payload )
{
    for( uint8_t byteIdx = 0u; 22u > byteIdx; byteIdx++ )
    {
        payload[ byteIdx ] = 0u;
    }

    for( uint16_t bitIdx = 0u; ( CRSF_RC_CHANNELS_CNT * CRSF_RC_CHANNEL_BITS ) > bitIdx; bitIdx++ )
    {
        const uint16_t value = channels.Channels[ bitIdx / CRSF_RC_CHANNEL_BITS ];

        if( 0u != ( value & ( 1u << ( bitIdx % CRSF_RC_CHANNEL_BITS ) ) ) )
        {
            payload[ bitIdx / 8u ] |= (uint8_t)( 1u << ( bitIdx % 8u ) );
        }
    }
}


/** \brief Appends 16 bit value (big endian) */
static void It_Crsf_Put16( uint8_t *buffer, crsf_MsgLength_t &length, uint16_t value )
{
    buffer[ length++ ] = (uint8_t)( value >> 8u );
    buffer[ length++ ] = (uint8_t)( value & 0xFFu );
}


/** \brief Appends 32 bit value (big endian) */
static void It_Crsf_Put32( uint8_t *buffer, crsf_MsgLength_t &length, uint32_t value )
{
    It_Crsf_Put16( buffer, length, (uint16_t)( value >> 16u ) );
    It_Crsf_Put16( buffer, length, (uint16_t)( value & 0xFFFFu ) );
}


/** \brief Appends null-terminated string (including terminator) */
static void It_Crsf_PutString( uint8_t *buffer, crsf_MsgLength_t &length, const char *text )
{
    for( uint8_t charIdx = 0u; '\0' != text[ charIdx ]; charIdx++ )
    {
        buffer[ length++ ] = (uint8_t)text[ charIdx ];
    }

    buffer[ length++ ] = 0u;
}


/**
 * \brief Builds expected parameter entry frame of parameter "Gain" (FLOAT)
 *
 * \param frame    [out]: Frame buffer
 * \param frameLen [out]: Frame length
 * \param value     [in]: Expected value
 */
static void It_Crsf_Build_FloatEntry( uint8_t *frame, crsf_MsgLength_t &frameLen, int32_t value )
{
    uint8_t          payload[ CRSF_PAYLOAD_MAX_LEN ];
    crsf_MsgLength_t payloadLen = 0u;

    payload[ payloadLen++ ] = itCrsf_ParamGain;     /* Parameter number   */
    payload[ payloadLen++ ] = 0u;                   /* Chunks remaining   */
    payload[ payloadLen++ ] = 0u;                   /* Parent folder      */
    payload[ payloadLen++ ] = CRSF_PARAM_FLOAT;
    It_Crsf_PutString( payload, payloadLen, "Gain" );
    It_Crsf_Put32( payload, payloadLen, (uint32_t)value );
    It_Crsf_Put32( payload, payloadLen, (uint32_t)itCrsf_GainMin );
    It_Crsf_Put32( payload, payloadLen, (uint32_t)itCrsf_GainMax );
    It_Crsf_Put32( payload, payloadLen, (uint32_t)itCrsf_GainDefault );
    payload[ payloadLen++ ] = itCrsf_GainDecimals;
    It_Crsf_Put32( payload, payloadLen, (uint32_t)itCrsf_GainStep );
    It_Crsf_PutString( payload, payloadLen, "x" );

    frameLen = It_Crsf_Build_ExtFrame( frame, CRSF_FRAMETYPE_PARAM_ENTRY, itCrsf_HandsetAddr, itCrsf_FcAddr, payload, payloadLen );
}

