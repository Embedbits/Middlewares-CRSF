/**
 * \brief Initializes time base, both stacks and their physical layers
 *
 * Transport layers initialize physical layers in the first task. The line is
 * left to settle, then the records and statistics are cleared.
 *
 * \param xferMode [in]: Data transfer mode of both physical layers
 */
static void It_Crsf_Init( usart_XferMode_t xferMode )
{
    It_Crsf_Init_TimeBase();

    itCrsf_HandsetPhy.Set_XferMode( xferMode );
    itCrsf_FcPhy.Set_XferMode( xferMode );

    itCrsf_HandsetCore.Set_DeviceAddr( itCrsf_HandsetAddr );
    itCrsf_FcCore.Set_DeviceAddr( itCrsf_FcAddr );

    itCrsf_HandsetCore.Set_FrameCallback( It_Crsf_HandsetFrameCallback );
    itCrsf_FcCore.Set_FrameCallback( It_Crsf_FcFrameCallback );

    itCrsf_FcRc.Set_ChannelsCallback( It_Crsf_RcChannelsCallback );
    itCrsf_FcRc.Set_LinkStateCallback( It_Crsf_LinkStateCallback );

    It_Crsf_Run( itCrsf_SettleTimeMs );

    TEST_ASSERT_TRUE_MESSAGE( itCrsf_HandsetPhy.Get_InitOk(), "RC side physical layer initialization failed" );
    TEST_ASSERT_TRUE_MESSAGE( itCrsf_FcPhy.Get_InitOk(),      "FC physical layer initialization failed" );
    TEST_ASSERT_EQUAL( CRSF_TL_ACTIVE, itCrsf_HandsetTl.Get_ModuleState() );
    TEST_ASSERT_EQUAL( CRSF_TL_ACTIVE, itCrsf_FcTl.Get_ModuleState() );

    itCrsf_HandsetPhy.Reset_Records();
    itCrsf_FcPhy.Reset_Records();
    itCrsf_HandsetTl.Reset_StatCounter();
    itCrsf_FcTl.Reset_StatCounter();
    itCrsf_FcLog.Cnt      = 0u;
    itCrsf_HandsetLog.Cnt = 0u;
}


/**
 * \brief Initializes and starts time base of CRSF tasks (TIM2, 1 MHz, free running)
 *        and timer of debug halt detection (TIM6, 5 kHz, free running, not frozen in halt)
 */
static void It_Crsf_Init_TimeBase( void )
{
    const tim_PeriphId_t timers[]      = { IT_CRSF_REF_TIM, IT_CRSF_HALT_TIM };
    const uint32_t       frequencies[] = { 1000000u,        itCrsf_HaltTimFreq };
    const tim_Counter_t  periods[]     = { 0xFFFFFFFFu,     0xFFFFu };

    for( uint8_t timIdx = 0u; ( sizeof( timers ) / sizeof( timers[ 0u ] ) ) > timIdx; timIdx++ )
    {
        tim_PeriphConfig_t timConfig;

        TEST_ASSERT_EQUAL( TIM_REQUEST_OK, Tim_Get_DefaultConfig( &timConfig ) );
        timConfig.PeriphId         = timers[ timIdx ];
        timConfig.TimerFrequency   = frequencies[ timIdx ];
        timConfig.RefreshFrequency = 1u;

        TEST_ASSERT_EQUAL( TIM_REQUEST_OK, Tim_Init( &timConfig ) );
        TEST_ASSERT_EQUAL( TIM_REQUEST_OK, Tim_Set_Period( timers[ timIdx ], periods[ timIdx ] ) );
        TEST_ASSERT_EQUAL( TIM_REQUEST_OK, Tim_Start( timers[ timIdx ] ) );
    }

    IT_CRSF_HALT_TIM_UNFREEZE();
}


/**
 * \brief Starts observation of debug halts (start of traffic)
 */
static void It_Crsf_HaltGuard_Mark( void )
{
    (void)Tim_Get_Counter( IT_CRSF_REF_TIM,  &itCrsf_HaltRefMark );
    (void)Tim_Get_Counter( IT_CRSF_HALT_TIM, &itCrsf_HaltTimMark );
}


/**
 * \brief Repeats the test case after reset if the traffic failed during debug halt
 *
 * Halt time is the difference of the halt timer (runs in halt) and the
 * reference timer (frozen in halt) since \ref It_Crsf_HaltGuard_Mark.
 * Without halt, after \ref itCrsf_RetryMax repetitions or without failure
 * the function returns and the test case checks the traffic.
 *
 * \param disturbed [in]: Traffic has transport failure
 */
static void It_Crsf_Retry_IfHalted( bool disturbed )
{
    tim_Counter_t refCnt  = 0u;
    tim_Counter_t haltCnt = 0u;

    (void)Tim_Get_Counter( IT_CRSF_REF_TIM,  &refCnt );
    (void)Tim_Get_Counter( IT_CRSF_HALT_TIM, &haltCnt );

    const uint32_t runUs   = refCnt - itCrsf_HaltRefMark;
    const uint32_t totalUs = (uint32_t)(uint16_t)( haltCnt - itCrsf_HaltTimMark ) * itCrsf_HaltTickUs;
    const bool     halted  = ( ( runUs + itCrsf_HaltMinUs ) <= totalUs );

    if( ( true == disturbed ) && ( true == halted ) && ( itCrsf_RetryMax > IntegrationTesting_Get_Stage() ) )
    {
        TEST_MESSAGE( "Debug halt disturbed USART, test repeated" );

        IntegrationTesting_Set_ResetExpected();

        Nvic_Set_SystemReset();
    }
    else if( true == disturbed )
    {
        /* Failure is reported by the test case */
        TEST_MESSAGE( ( true == halted ) ? "Transport failure during debug halt, repetitions exhausted"
                                         : "Transport failure without debug halt" );
    }
    else
    {
        /* Traffic is checked by the test case */
    }
}


/** \brief One task period of both stacks */
static void It_Crsf_Tick( void )
{
    itCrsf_HandsetCore.Task( itCrsf_TaskTimeMs );
    itCrsf_FcCore.Task( itCrsf_TaskTimeMs );
}


/**
 * \brief Runs both stacks with 1 ms task period until condition is fulfilled or timeout
 *
 * \param condition [in]: Callable returning true when waiting is finished
 * \param timeoutMs [in]: Maximal waiting time [ms]
 *
 * \return Final value of condition
 */
template< typename CONDITION >
static bool It_Crsf_RunUntil( CONDITION condition, uint32_t timeoutMs )
{
    tim_Counter_t lastCnt   = 0u;
    tim_Counter_t actualCnt = 0u;
    uint32_t      elapsedMs = 0u;

    (void)Tim_Get_Counter( IT_CRSF_REF_TIM, &lastCnt );

    while( ( false == condition() ) && ( timeoutMs > elapsedMs ) )
    {
        (void)Tim_Get_Counter( IT_CRSF_REF_TIM, &actualCnt );

        if( itCrsf_TaskPeriodUs <= ( actualCnt - lastCnt ) )
        {
            lastCnt += itCrsf_TaskPeriodUs;
            elapsedMs++;

            if( nullptr != itCrsf_TickHook )
            {
                itCrsf_TickHook( elapsedMs );
            }

            It_Crsf_Tick();
        }
        else
        {
            /* Data handling in polling mode */
            Usart_Task();
        }
    }

    return ( condition() );
}


/**
 * \brief Runs both stacks for given time
 *
 * \param timeMs [in]: Time [ms]
 */
static void It_Crsf_Run( uint32_t timeMs )
{
    (void)It_Crsf_RunUntil( []() { return ( false ); }, timeMs );
}


